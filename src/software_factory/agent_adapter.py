def _extract_code(text: str) -> str:
    """Extract code from markdown code fences or return cleaned text."""
    pattern = re.compile(r"```(?:[a-zA-Z0-9_\-]+)?\s*\n(.*?)\n```", re.DOTALL)
    match = pattern.search(text)
    if match:
        return match.group(1).strip()
    return text.strip()


